// Renders README.md from the theme's template, scripts/themes/<theme>/README.template.md.
//
// Templates are plain Markdown/HTML plus a few {{tokens}}. Text arguments are quoted:
//   {{img name "alt"}}          a dark/light <picture> of a generated image
//   {{projects "header alt"}}   one clickable image per pinned repo (kept in sync with the pins)
//   {{query "intro"}}           "query my profile" buttons and the last result; {login} in the intro
//                               becomes the GitHub login
//   {{links}}                   the profile.config.json links as image buttons
//   {{ratings}}                 Matchday: how each rating is calculated, as a table
//   {{owls}}                    Wizarding: how each subject is graded, and the grade bands
//   {{sorting}}                 Wizarding: which subjects each house is sorted on
//
// The tables only describe the rules, never this build's scores: the workflow commits
// the README whenever it changes, and live numbers would change it every 6 hours.

import { SCHEMA } from './query/guard.mjs';
import { ATTRIBUTES } from './ratings.mjs';
import { GRADES, SUBJECTS } from './themes/wizarding/owls.mjs';
import { HOUSES } from './themes/wizarding/sorting.mjs';

const START = '<!-- projects:start (generated by scripts/build.mjs, edit the pins instead) -->';
const END = '<!-- projects:end -->';
const QSTART = '<!-- query:start (generated by scripts/build.mjs from profile.config.json) -->';
const QEND = '<!-- query:end -->';

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

export const imageUrl = (login, name, theme) =>
  `https://github.com/${login}/${login}/blob/output/profile/${name}-${theme}.svg?raw=true`;

export function picture(login, name, alt, width = '100%') {
  return `<picture>
    <source media="(prefers-color-scheme: dark)" srcset="${imageUrl(login, name, 'dark')}" />
    <img alt="${esc(alt)}" src="${imageUrl(login, name, 'light')}"${width ? ` width="${width}"` : ''} />
  </picture>`;
}

const inline = (html) => html.replace(/\n\s*/g, '');

export function projectsBlock(d, headerAlt = 'Pinned projects') {
  const rows = d.pinned.map((r, i) => {
    const alt = `${r.name}: ${r.about}`;
    return `<a href="${esc(r.url)}">\n  ${picture(d.login, `project-${i + 1}`, alt)}\n</a>`;
  });
  return [
    START,
    picture(d.login, 'projects-header', headerAlt),
    ...rows,
    picture(d.login, 'projects-footer', `${d.pinned.length} pinned projects`),
    END,
  ].join('\n');
}

const QUERY_BODY = (tables) => `Submit this issue as it is and a GitHub Action runs the query on QueryLens, my toy SQL engine. It replies here and shows the result on my profile within a minute.

To write your own query, edit the title and keep the \`sql:\` prefix. You can query:
${tables}

Only SELECT and EXPLAIN run, and a query may only use SQL keywords, these table and column names, numbers, and values that appear in the data.`;

const QUERY_INTRO = 'Run SQL against this profile. Pick a query to open a pre-filled issue: a GitHub Action runs it on [QueryLens](https://github.com/{login}/query-lens), my toy database engine, replies on the issue, and puts the result here within a minute. Edit the issue title to write your own.';

export function queryBlock(login, queries, schema, intro = QUERY_INTRO) {
  const tables = Object.entries(schema).map(([t, cols]) => `- \`${t}\` (${cols.join(', ')})`).join('\n');
  const body = encodeURIComponent(QUERY_BODY(tables));
  const resultUrl = (theme) => `https://github.com/${login}/${login}/blob/query/query-result-${theme}.svg?raw=true`;
  const buttons = queries.map((q, i) => {
    const href = `https://github.com/${login}/${login}/issues/new?title=${encodeURIComponent(`sql: ${q.sql}`)}&body=${body}`;
    return `<a href="${esc(href)}">${inline(picture(login, `query-${i + 1}`, `Run: ${q.label}`, null))}</a>`;
  });
  return [
    QSTART,
    intro.replaceAll('{login}', login),
    '',
    `<picture>
    <source media="(prefers-color-scheme: dark)" srcset="${resultUrl('dark')}" />
    <img alt="The last query a visitor ran on this profile" src="${resultUrl('light')}" width="100%" />
  </picture>`,
    '',
    buttons.join(' '),
    QEND,
  ].join('\n');
}

export const linksLine = (login, links) =>
  links.map((l) => `<a href="${esc(l.url)}">${inline(picture(login, `link-${l.label}`, l.label, null))}</a>`).join(' ');

export function ratingsTable() {
  const pct = (w) => `${Math.round(w * 100)}%`;
  return [
    '| Rating | What it means | Calculated from | Weight in overall |',
    '| :--- | :--- | :--- | ---: |',
    ...ATTRIBUTES.map((a) => `| **${a.label}** (${a.key}) | ${a.means} | ${a.how} | ${pct(a.weight)} |`),
  ].join('\n');
}

const RATING_MIN = 40, RATING_MAX = 99; // ratings.mjs FLOOR and FLOOR + SPAN

export function owlsTable() {
  const pct = (w) => `${Math.round(w * 100)}%`;
  const band = (g, i) => {
    const lo = Math.max(g.min, RATING_MIN);
    const hi = i === 0 ? RATING_MAX : GRADES[i - 1].min - 1;
    return lo === hi ? `${lo}` : `${lo}–${hi}`;
  };
  return [
    '| Subject | What it measures | Calculated from | Weight in overall |',
    '| :--- | :--- | :--- | ---: |',
    ...ATTRIBUTES.map((a) => `| **${SUBJECTS[a.key]}** | ${a.means} | ${a.how} | ${pct(a.weight)} |`),
    '',
    '| Grade | Score |',
    '| :--- | :--- |',
    ...GRADES.map((g, i) => `| **${g.letter}** · ${g.name} | ${band(g, i)} |`),
  ].join('\n');
}

export function sortingTable() {
  const means = Object.fromEntries(ATTRIBUTES.map((a) => [a.key, a.means]));
  return [
    '| House | Sorted for | Score is the mean of |',
    '| :--- | :--- | :--- |',
    ...HOUSES.map((h) => `| **${h.name}** | ${h.trait} | ${h.from.map((k) => `${SUBJECTS[k]} (${means[k]})`).join(' and ')} |`),
  ].join('\n');
}

/** Fills a README template. Unknown tokens are an error, so typos don't ship. */
export function renderReadme(template, d, cfg) {
  return template.replace(/\{\{(\w+)((?:\s+(?:"[^"]*"|[\w-]+))*)\s*\}\}/g, (match, name, rawArgs) => {
    const args = [...rawArgs.matchAll(/"([^"]*)"|([\w-]+)/g)].map((m) => m[1] ?? m[2]);
    switch (name) {
      case 'img': return picture(d.login, args[0], args[1] ?? args[0]);
      case 'projects': return projectsBlock(d, args[0]);
      case 'query': return cfg?.queries?.length ? queryBlock(d.login, cfg.queries, SCHEMA, args[0]) : '';
      case 'links': return linksLine(d.login, cfg.links ?? []);
      case 'ratings': return ratingsTable();
      case 'owls': return owlsTable();
      case 'sorting': return sortingTable();
      default: throw new Error(`README template: unknown token ${match}`);
    }
  });
}
