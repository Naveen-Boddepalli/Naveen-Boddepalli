// Keeps the README's projects block in sync with the pinned repos.
// Only the text between the markers is rewritten.

const START = '<!-- projects:start (generated by scripts/build.mjs, edit the pins instead) -->';
const END = '<!-- projects:end -->';

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

export const imageUrl = (login, name, theme) =>
  `https://github.com/${login}/${login}/blob/output/profile/${name}-${theme}.svg?raw=true`;

export function picture(login, name, alt, width = '100%') {
  return `<picture>
    <source media="(prefers-color-scheme: dark)" srcset="${imageUrl(login, name, 'dark')}" />
    <img alt="${esc(alt)}" src="${imageUrl(login, name, 'light')}"${width ? ` width="${width}"` : ''} />
  </picture>`;
}

export function projectsBlock(d) {
  const rows = d.pinned.map((r, i) => {
    const alt = `${r.name}: ${r.about}`;
    return `<a href="${esc(r.url)}">\n  ${picture(d.login, `project-${i + 1}`, alt)}\n</a>`;
  });
  return [
    START,
    picture(d.login, 'projects-header', 'SELECT name, about, lang, pushed, demo FROM pinned;'),
    ...rows,
    picture(d.login, 'projects-footer', `${d.pinned.length} pinned projects`),
    END,
  ].join('\n');
}

export function syncReadme(text, d) {
  const a = text.indexOf('<!-- projects:start'), b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error('README is missing the projects:start / projects:end markers');
  return text.slice(0, a) + projectsBlock(d) + text.slice(b + END.length);
}
